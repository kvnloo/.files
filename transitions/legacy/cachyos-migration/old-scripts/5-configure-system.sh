# ===================================
# MAIN EXECUTION
# ===================================

main() {
    log "Starting system configuration..."
    log "Backup directory: $BACKUP_DIR"
    log "Log file: $LOG_FILE"

    configure_sysctl
    configure_systemd_limits
    configure_pam_limits
    configure_io_scheduler
    configure_mount_options
    configure_bootloader
    configure_cpu_governor

    verify_configuration
    generate_summary

    log ""
    log "${GREEN}✅ Configuration completed successfully!${NC}"
    log "📁 Backups: $BACKUP_DIR"
    log "📝 Log: $LOG_FILE"
    log ""
    log "${YELLOW}⚠️  REBOOT REQUIRED to apply all changes${NC}"
    log "After reboot, run: 6-restore-configs.sh"
}

main
