"""Ordered, repository-local legacy input and deterministic native Lua translation.

Runtime pywal/monitor files remain independently generated overlays. This module
never reads the live desktop or reloads it. Agent seats deliberately use the
private special workspace rather than the legacy visible workspace nine.
"""
import json
import re
from pathlib import Path


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def scalar(value):
    gradient = re.fullmatch(r'((?:rgba?\([^)]+\)\s+)+)(\d+)deg', value)
    if gradient:
        colors = re.findall(r'rgba?\([^)]+\)', gradient[1])
        return '{colors={' + ','.join(quote(color) for color in colors) + '},angle=' + gradient[2] + '}'
    if value in {'true', 'false'} or re.fullmatch(r'-?\d+(?:\.\d+)?|0x[0-9a-fA-F]+', value):
        return value
    return quote(value)


def key(value):
    value = value.replace('-', '_')
    return value if re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', value) else '[' + quote(value) + ']'


def table(values):
    return '{' + ','.join(key(k) + '=' + (table(v) if isinstance(v, dict) else v) for k, v in values.items()) + '}'


def read_directives(root):
    """Expand checked-in sources at their occurrence, retaining duplicate writes."""
    base = root / 'config/hyprland'
    active = []
    records = []
    def visit(path):
        path = path.resolve()
        if path in active:
            raise ValueError('recursive legacy source: ' + str(path))
        active.append(path)
        stack = []
        block_stacks = []
        for number, raw in enumerate(path.read_text().splitlines(), 1):
            text = raw.split('#', 1)[0].strip()
            if not text:
                continue
            if text.endswith('{'):
                block_stacks.append(list(stack))
                stack.extend(text[:-1].strip().split(':'))
                continue
            if text == '}':
                stack[:] = block_stacks.pop()
                continue
            if '=' not in text:
                raise ValueError(f'{path}:{number}: unsupported directive {text}')
            name, value = (part.strip() for part in text.split('=', 1))
            if name == 'source' and value.endswith('/config/hermes-liquid-glass/hypr/liquid-glass.conf'):
                continue  # generated/liquid_glass.lua owns this external package
            if name == 'source':
                marker = '/.files/'
                if marker in value:
                    visit(root / value.split(marker, 1)[1])
                elif value.startswith('~/.cache/wal/'):
                    pass  # generated palette owns this runtime input
                else:
                    raise ValueError(f'unsupported source: {value}')
                continue
            records.append({'file': str(path.relative_to(root)), 'line': number,
                            'path': '.'.join([*stack, name]).replace(':', '.'),
                            'name': name, 'value': value, 'stack': list(stack)})
        if stack:
            raise ValueError(f'unclosed legacy blocks: {path}: {stack}')
        active.pop()
    visit(base / 'hyprland.legacy.conf')
    return records


def generate(root, owners=None):
    records = read_directives(root)
    outputs = {name: ['-- Generated by scripts/build-hypr-lua-static-owners; edit legacy sources, then regenerate.']
               for name in ('appearance', 'rules', 'binds', 'environment', 'autostart')}
    appearance = outputs['appearance']
    appearance.extend(['local home = assert(os.getenv("HOME"))',
        'if os.getenv("HYPR_LUA_TEST_MODE") ~= "1" or os.getenv("HYPR_LUA_ISOLATED_MODE") == "1" then',
        '  hl.plugin.load(os.getenv("HYPR_LUA_PLUGIN") or (home .. "/.local/share/hyprland/plugins/hyprglass-next/hyprglass.so"))', 'end'])
    configs = {}
    presets = {}
    devices = []
    device = None
    variables = {'HOME': '$HOME'}
    submap = 'reset'
    binding_lines = []
    commands = []
    def expand(value):
        for _ in range(len(variables) + 1):
            updated = re.sub(r'\$([A-Za-z_][A-Za-z_0-9]*)', lambda m: variables.get(m[1], m[0]), value)
            if updated == value:
                return value
            value = updated
        raise ValueError('recursive legacy variable: ' + value)
    def keys(value):
        mods, button = (part.strip() for part in value.split(',', 1))
        return ' + '.join([*expand(mods).split(), button])
    for record in records:
        name, value, path = record['name'], record['value'], record['path']
        stack = record['stack']
        if name.startswith('$'):
            variables[name[1:]] = expand(value)
            continue
        value = expand(value)
        if name in {'exec-once', 'exec'} and not stack:
            commands.append(value)
        if name in {'monitor', 'workspace', 'exec-once', 'exec', 'plugin'} and not stack:
            continue  # runtime/monitor owners stay separate
        if name == 'env' and not stack:
            env, val = value.split(',', 1)
            outputs['environment'].append(f'hl.env({quote(env.strip())}, {quote(val.strip())})')
        elif name == 'submap':
            if submap != 'reset':
                binding_lines.append('end)')
            submap = value
            if submap != 'reset':
                binding_lines.append(f'hl.define_submap({quote(value)}, "reset", function()')
        elif name == 'unbind':
            binding_lines.append(f'hl.unbind({quote(keys(value))})')
        elif name.startswith('bind'):
            parts = [p.strip() for p in value.split(',', 3)]
            mods, button, dispatcher = parts[:3]
            arg = parts[3] if len(parts) == 4 else ''
            flags = name[4:]
            opts = {target: 'true' for flag, target in [('l','locked'),('e','repeating'),('o','long_press'),('i','ignore_mods'),('n','non_consuming'),('r','release')] if flag in flags}
            if name == 'bindm':
                opts['mouse'] = 'true'
                dispatch = {'movewindow': 'hl.dsp.window.drag()', 'resizewindow': 'hl.dsp.window.resize()'}[dispatcher]
            else:
                dispatch = f'hl.dsp.exec_raw({quote(dispatcher)}, {quote(arg)})'
            binding_lines.append(f'hl.bind({quote(keys(mods + "," + button))}, {dispatch}' + (', ' + table(opts) if opts else '') + ')')
        elif name in {'windowrule', 'layerrule'}:
            match, props = {}, {}
            for part in value.split(','):
                prop, val = part.strip().split(' ', 1)
                if prop.startswith('match:'):
                    match[prop[6:]] = quote(val)
                else:
                    if prop == 'workspace' and val == '9 silent':
                        val = 'special:hermes-tests silent'
                    props[prop] = quote(val) if prop == 'workspace' else {'on': 'true', 'off': 'false'}.get(val, scalar(val))
            props = {'name': quote('legacy-' + str(len(outputs['rules']))), 'match': table(match), **props}
            outputs['rules'].append('hl.' + ('window_rule' if name == 'windowrule' else 'layer_rule') + '(' + table(props) + ')')
        elif stack == ['device']:
            if name == 'name':
                device = {}
                devices.append(device)
            if device is None:
                raise ValueError('device requires name first')
            device[name] = scalar(value)
        elif name == 'bezier' and stack in ([], ['animations']):
            curve, x1, y1, x2, y2 = [p.strip() for p in value.split(',')]
            appearance.append(f'hl.curve({quote(curve)}, {{type="bezier",points={{{{{x1},{y1}}},{{{x2},{y2}}}}}}})')
        elif name == 'animation' and stack in ([], ['animations']):
            parts = [p.strip() for p in value.split(',')]
            fields = dict(zip(['leaf','enabled','speed','bezier','style'], [quote(parts[0]), 'true' if parts[1] == '1' else 'false', parts[2], quote(parts[3]), *[quote(p) for p in parts[4:]]]))
            appearance.append('hl.animation(' + table(fields) + ')')
        elif name in {'gesture', 'spatialoverview-gesture'}:
            parts = [p.strip() for p in value.split(',')]
            fields = {'fingers': parts[0], 'direction': quote(parts[1])}
            if name == 'spatialoverview-gesture':
                # The plugin owns its native gesture API, just like phantomat.lua.
                appearance.extend([
                    'if os.getenv("HYPR_LUA_TEST_MODE") ~= "1" then',
                    'hl.plugin.load(os.getenv("HYPR_LUA_PHANTOMAT_PLUGIN") or (home .. "/.local/share/hyprland/plugins/phantomat/spatialoverview.so"))',
                    'hl.on("hyprland.start", function() local so=hl.plugin.spatialoverview; if not so then error("spatialoverview Lua API unavailable") end; so.gesture(' + table({**fields, 'action': quote(parts[2])}) + ') end)',
                    'end',
                ])
                continue
            if parts[2] == 'dispatcher':
                fields['action'] = 'function() hl.dispatch(hl.dsp.exec_raw(' + quote(parts[3]) + ', ' + quote(', '.join(parts[4:])) + ')) end'
            else:
                fields['action'] = quote(parts[2])
                if len(parts) > 3:
                    fields['workspace_name'] = quote(parts[3])
            appearance.append('hl.gesture(' + table(fields) + ')')
        else:
            # Scalar leaves use last-write-wins, repeated plugin preset directives
            # remain ordered calls rather than being collapsed into a Lua table.
            parts = path.split('.')
            if name == 'preset' and parts[:2] == ['plugin','hyprglass'] and len(parts) == 3:
                fields = dict(part.strip().split(':', 1) for part in value.split(','))
                preset_name = fields.pop('name').split(':')
                node = presets.setdefault(preset_name[0], {})
                if len(preset_name) > 1:
                    node = node.setdefault(preset_name[1], {})
                node.update({k: scalar(v) for k, v in fields.items()})
            else:
                configs[path] = scalar(value)
    if submap != 'reset':
        binding_lines.append('end)')
    tree = {}
    for path, value in configs.items():
        node = tree
        parts = path.split('.')
        for part in parts[:-1]:
            node = node.setdefault(part, {})
        node[parts[-1]] = value
    plugins = tree.pop('plugin', {})
    appearance.append('hl.config(' + table(tree) + ')')
    appearance.extend([
        'if os.getenv("HYPR_LUA_TEST_MODE") ~= "1" or os.getenv("HYPR_LUA_ISOLATED_MODE") == "1" then',
        'hl.on("hyprland.start", function()',
        '  local hg=hl.plugin.hyprglass',
        '  if not hg then error("hyprglass Lua API unavailable after plugin load") end',
        '  hl.config(' + table({'plugin': plugins}) + ')',
    ])
    for preset_name, values in presets.items():
        appearance.append('  hg.preset(' + quote(preset_name) + ', ' + table(values) + ')')
    appearance.extend(['end)', 'end'])
    appearance.extend('hl.device(' + table(d) + ')' for d in devices)
    appearance.extend(['-- The runtime palette is applied by lua.bridges from generated Lua, never sourced hyprlang.',
                       'if os.getenv("HYPR_LUA_TEST_MODE") == "1" then hl.config({xwayland={enabled=false}}) end'])
    outputs['binds'].extend(binding_lines)
    outputs['autostart'].extend([
        'local home=assert(os.getenv("HOME"))',
        'if os.getenv("HYPR_LUA_TEST_MODE") == "1" or os.getenv("HYPR_LUA_ISOLATED_MODE") == "1" then return end',
        'hl.on("hyprland.start", function()',
    ])
    outputs['autostart'].extend('  hl.exec_cmd(' + quote(cmd).replace('$HOME', '"..home.."') + ')' for cmd in commands)
    outputs['autostart'].append('end)')
    for name, lines in outputs.items():
        if owners is not None and name not in owners:
            continue
        (root / 'config/hyprland/lua' / (name + '.lua')).write_text('\n'.join(lines) + '\n')
